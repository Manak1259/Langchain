text="""
the king loved the queen and the queen loved the king
the king loved playing cricket in the garden
the queen loved playing chess in the palace
the king and the queen walked in the garden
the kingloved the kingdom and the people loved the king"""

# print(text)

words=text.lower().split()
# print("the length of words is: {len(words)}")
# print(f'First ten words:{words[:10]}')

pair_counts= {}

for i in range(len(words)-1):
    current_word = words[i]
    next_word = words[i+1]
  

    #if we haven't seen the current word>>> create empty dictionary

    if current_word not in pair_counts:
        pair_counts[current_word]={}
    if next_word not in pair_counts[current_word]:
        pair_counts[current_word][next_word]=0 # if next word is not dic then create new value by initializing valure of 0
       

    pair_counts[current_word][next_word]+=1


print(pair_counts)
# now need to calculate the probability
pair_probs = {}

for current_word in pair_counts:
    pair_probs[current_word]={}
    total = sum(pair_counts[current_word].values()) #15

    for next_word in pair_counts[current_word]: #king
        pair_probs[current_word][next_word]=pair_counts[current_word][next_word]/ total



print("probalities after the")
for word, prob in sorted(pair_probs['the'].items(), key=lambda x: -x[1]):
    print(f"{word}: {prob:.1%}")



import random

def generate_token(start_word, num_word=20):
    current_word = start_word
    output = [current_word]

    for _ in range(num_word):
        if current_word not in pair_probs:
            break

        options = list(pair_probs[current_word].keys())
        probabilities = list(pair_probs[current_word].values())

        next_word = random.choices(options, weights=probabilities, k=1)[0]
        output.append(next_word)
        current_word = next_word

    return " ".join(output)

print("text generated by Bigram Model:")

for i in range(5):
    print(f"{i+1}. {generate_token('the')}")


